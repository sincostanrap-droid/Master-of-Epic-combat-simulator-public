const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const scope=vm.createContext({});vm.runInContext(fs.readFileSync('src/calc/sustainedAttack.js','utf8'),scope);
const simulate=scope.MOESustainedAttack.simulate;
const buff={name:'A',durationSeconds:10,sustainDowntimeSeconds:2};
let r=simulate({seconds:30,buffs:[buff],evaluate:a=>({supported:true,dps:a.length?100:50})});
assert.equal(r.totalDamage,2600);assert.equal(r.downtimeSeconds,4);assert.equal(r.refreshes[0].count,2);
assert.equal(r.averageDps,2600/30);assert.equal(r.evaluations,1);
r=simulate({seconds:10,buffs:[{...buff,sustainDowntimeSeconds:undefined}],evaluate:()=>({supported:true,dps:100})});
assert.equal(r.totalDamage,1000,'no refresh at endpoint; no cost needed');
r=simulate({seconds:30,buffs:[{...buff,sustainMode:'once'}],evaluate:a=>({supported:true,dps:a.length?100:50})});
assert.equal(r.totalDamage,2000);assert.equal(r.evaluations,2);
r=simulate({seconds:30,buffs:[buff,{name:'B',durationSeconds:10,sustainDowntimeSeconds:3}],evaluate:a=>({supported:true,dps:a.length*100})});
assert.equal(r.downtimeSeconds,10,'overlapping refreshes are sequential');assert.equal(r.totalDamage,4000);
r=simulate({seconds:11,buffs:[{name:'unknown',durationSeconds:10}],evaluate:()=>{throw Error('must not evaluate');}});
assert.equal(r.supported,false);assert.equal(r.totalDamage,null);
r=simulate({seconds:30,buffs:[{...buff,sustainDowntimeSeconds:0}],evaluate:()=>({supported:true,dps:100})});
assert.equal(r.totalDamage,3000,'explicit zero is supported');
r=simulate({seconds:30,buffs:[{name:'constant',sustainMode:'maintained'}],evaluate:()=>({supported:true,dps:100})});
assert.equal(r.totalDamage,3000);
r=simulate({seconds:30,buffs:[{name:'unknown',durationSeconds:0}],evaluate:()=>({supported:true,dps:100})});
assert.equal(r.supported,false,'zero duration is not permanent');
r=simulate({seconds:30,buffs:[{...buff,sustainMode:'once'}],evaluate:a=>a.length?{supported:true,dps:100}:{supported:false,reasons:['missing formula']}});
assert.equal(r.totalDamage,null,'unsupported segment is not zero');
r=simulate({seconds:30,buffs:[{...buff,durationSeconds:0.001,sustainDowntimeSeconds:0}],maxEvents:10,evaluate:()=>({supported:true,dps:100})});
assert.equal(r.supported,false,'bounded workload');
console.log('Sustained timing: prebuff, expiry, sequential refresh, boundaries, cache, unknown and zero passed');
